#!/usr/bin/env node
// Generates src/lib/api/schema.gen.ts from the backend's OpenAPI document.
// Usage: node scripts/generate-api-types.mjs [path/to/openapi.json]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const input = resolve(process.argv[2] ?? resolve(root, '../backend/openapi.json'))
const output = resolve(root, 'src/lib/api/schema.gen.ts')
const doc = JSON.parse(readFileSync(input, 'utf8'))

const typeName = (name) => name.replace(/[^A-Za-z0-9_]/g, '_').replace(/_+$/, '')
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name))

function type(schema) {
  if (!schema || Object.keys(schema).length === 0) return 'unknown'
  if (schema.$ref) return typeName(schema.$ref.split('/').pop())
  if (schema.const !== undefined) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  const union = schema.anyOf ?? schema.oneOf
  if (union) return [...new Set(union.map(type))].join(' | ')
  if (schema.allOf) return schema.allOf.map(type).join(' & ')
  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array': {
      const item = type(schema.items)
      return /[|&]/.test(item) ? `(${item})[]` : `${item}[]`
    }
    case 'object':
      if (schema.properties) return objectType(schema)
      if (schema.additionalProperties && schema.additionalProperties !== true) {
        return `Record<string, ${type(schema.additionalProperties)}>`
      }
      return 'Record<string, unknown>'
    default:
      return 'unknown'
  }
}

function objectType(schema, indent = '') {
  const required = new Set(schema.required ?? [])
  const lines = Object.entries(schema.properties ?? {}).map(([name, property]) => {
    const optional = required.has(name) ? '' : '?'
    return `${indent}  ${key(name)}${optional}: ${type(property)}`
  })
  return `{\n${lines.join('\n')}\n${indent}}`
}

const schemas = doc.components?.schemas ?? {}
const body = Object.entries(schemas)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, schema]) => {
    const id = typeName(name)
    if (schema.type === 'object' || schema.properties) return `export interface ${id} ${objectType(schema)}`
    return `export type ${id} = ${type(schema)}`
  })
  .join('\n\n')

writeFileSync(
  output,
  `// Generated by scripts/generate-api-types.mjs from backend/openapi.json (${doc.info?.title ?? 'API'} ${doc.info?.version ?? ''}).\n// Do not edit by hand; run \`pnpm --dir frontend api:types\` after the backend schema changes.\n\n${body}\n`,
)
console.log(`Wrote ${Object.keys(schemas).length} schemas to ${output}`)
